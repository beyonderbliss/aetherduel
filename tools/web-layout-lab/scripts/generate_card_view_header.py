#!/usr/bin/env python3
"""Generate the native C++ constants for the card-view layout from JSON."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SPEC = ROOT / "tools/web-layout-lab/layout-spec/card-view.json"
OUTPUT = ROOT / "gframe/card_view_layout.generated.h"


def render_header(spec: dict) -> str:
    if spec.get("schema_version") != 1:
        raise ValueError("Unsupported card-view layout schema_version")

    fullscreen = spec["fullscreen"]
    ratio = fullscreen["artwork_aspect_ratio"]
    origin = fullscreen["origin"]

    width = ratio["width"]
    height = ratio["height"]
    x = origin["x"]
    y = origin["y"]

    for name, value in {
        "aspect width": width,
        "aspect height": height,
    }.items():
        if not isinstance(value, int) or value <= 0:
            raise ValueError(f"{name} must be a positive integer")
    for name, value in {"origin x": x, "origin y": y}.items():
        if not isinstance(value, int):
            raise ValueError(f"{name} must be an integer")
    if fullscreen.get("height") != "viewport":
        raise ValueError('fullscreen.height must be "viewport"')

    return f"""// Generated by tools/web-layout-lab/scripts/generate_card_view_header.py.
// Source: tools/web-layout-lab/layout-spec/card-view.json
// Do not edit this file manually.

#ifndef YGO_CARD_VIEW_LAYOUT_GENERATED_H
#define YGO_CARD_VIEW_LAYOUT_GENERATED_H

namespace ygo {{
namespace layout {{

static constexpr int kFullscreenAspectWidth = {width};
static constexpr int kFullscreenAspectHeight = {height};
static constexpr int kFullscreenOriginX = {x};
static constexpr int kFullscreenOriginY = {y};

}} // namespace layout
}} // namespace ygo

#endif // YGO_CARD_VIEW_LAYOUT_GENERATED_H
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="fail if the checked-in header differs from generated output")
    args = parser.parse_args()

    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    generated = render_header(spec)

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(f"Out of date: {OUTPUT.relative_to(ROOT)}")
            return 1
        print("Card-view generated header is up to date.")
        return 0

    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
